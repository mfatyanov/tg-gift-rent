/**
 * Все тексты страницы. Правьте здесь — вёрстку трогать не нужно.
 *
 * Мини-разметка внутри строк:
 *   **жирный**                  — жирный текст
 *   [[Connect TON]]             — «псевдокнопка»-чип: так выглядит кнопка на сайте (нажать нельзя)
 *   [[!Transfer to Telegram]]   — красный чип: кнопка, которую НЕ нужно нажимать
 *   `tc://`                     — моноширинный текст (код, ссылка)
 *   [fragment.com](https://fragment.com) — ссылка, откроется в новой вкладке
 *
 * Никаких контактов вне площадок (Telegram, ВК и т.п.) — только «пишите в чат заказа».
 */

export interface Badge {
  emoji: string
  text: string
}

export interface InfoItem {
  emoji: string
  title: string
  text: string
}

export interface Shot {
  /** Файл из public/steps/ (готовит npm run shots, см. scripts/shots.config.mjs) */
  file: string
  /** Что на картинке — для незрячих и если картинка не загрузилась */
  alt: string
}

export interface Step {
  n: number
  emoji: string
  title: string
  /** Абзацы шага — по одному действию на абзац */
  text: string[]
  /** Короткая подсказка внизу карточки */
  tip?: string
  /** Жёлтый стикер-предупреждение над карточкой шага */
  warning?: string
  /** 0–2 скриншота; пустой массив — плейсхолдер «скриншот шага N» */
  shots: Shot[]
}

export interface StepPart {
  emoji: string
  kicker: string
  title: string
  /** Номера шагов из массива steps */
  steps: number[]
}

export interface Warning extends InfoItem {
  tone: 'warn' | 'danger'
}

export interface FaqItem {
  q: string
  a: string
}

